-- ============================================================
-- 沧元界 · 神尊名号格式升级（myth_name 回填「·四位编号」）
-- 背景：注册/游客名号统一为「称号·编号」格式（如「盘古真君·1234」、
--       「游历散修·1234」），本脚本为历史记录补上编号，保持全站一致。
-- 编号规则：1000 + (id * 137 % 9000)，137 与 9000 互质，按 id 散列且互不相同。
-- 可重复执行：已带「·」的记录会被跳过。
-- ============================================================

UPDATE avatar_foundation
SET myth_name = CONCAT(myth_name, '·', LPAD(1000 + ((id * 137) % 9000), 4, '0'))
WHERE myth_name NOT LIKE '%·%';

-- 校验：应全部带「·编号」
SELECT id, deity_name, myth_name FROM avatar_foundation ORDER BY id;
